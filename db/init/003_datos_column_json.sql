-- jsonb NO preserva el orden de las claves de un objeto JSON (Postgres lo
-- reordena internamente). Cambiar `datos` a `json` (que sí preserva el
-- texto original tal cual se insertó) evita que ese reordenamiento llegue
-- siquiera a Python. `dgii_respuesta` se deja como jsonb: es solo para
-- mostrar la respuesta cruda de la DGII, su orden no importa.
--
-- NOTA: xml_builder.py::construir_xml_ecf ahora reordena cada nivel de
-- `datos` según la secuencia real del XSD (derivada del propio XSD, ver
-- `_orden_elementos`) antes de construir el XML, así que esta migración ya
-- NO es estrictamente necesaria para que el XML salga bien ordenado -- esa
-- capa de defensa vive en el código, no en el tipo de columna. Aun así,
-- aplicar esta migración (o mantener `json`) sigue siendo recomendable: es
-- gratis y preserva el texto exacto insertado.
ALTER TABLE facturacion.facturas ALTER COLUMN datos TYPE json USING datos::json;
