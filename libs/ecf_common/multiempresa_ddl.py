"""DDL común de la multiempresa (ver libs/ecf_common/empresa.py y
docs/MULTIEMPRESA.md).

`DDL_MULTIEMPRESA` lo corre cada servicio con migraciones (facturas-api,
inventario-api, erp-api y formato-606) al final de las suyas, con el
advisory lock compartido `LOCK_MULTIEMPRESA` (arrancan a la vez y crean las
mismas tablas), y después aísla sus propias tablas con
`configuracion.kontara_aislar(tabla, índices únicos)`. Es idempotente y
consulta el catálogo antes de cada ALTER: en una base ya migrada no toma
locks de tabla. `db/init/021_multiempresa.sql` contiene exactamente el mismo
DDL (lo verifican las pruebas de migraciones de cada servicio).

La empresa 1 (la de siempre) se crea con los datos de
`configuracion.empresa` si ya existen o con EMISOR_RNC /
EMISOR_RAZON_SOCIAL (`kontara.emisor_rnc` / `kontara.emisor_razon_social`,
set_config local a la transacción; ver `preparar_semilla`).
"""
from __future__ import annotations

from typing import Any

# Clave del advisory lock que comparten todos los servicios para este DDL
# (distinta de la de cada servicio).
LOCK_MULTIEMPRESA = 7_000_021

DDL_MULTIEMPRESA = """
CREATE SCHEMA IF NOT EXISTS configuracion;

-- Empresas (emisores) de la instalación. La 1 es la de siempre (todas las
-- filas que existían antes de la multiempresa quedan en ella); las nuevas
-- empiezan en 2. `rnc` solo dígitos. `estado` = 'inactiva' la oculta del
-- selector y corta el acceso, sin borrar nada.
CREATE TABLE IF NOT EXISTS configuracion.empresas (
    id                   integer GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    rnc                  text,
    razon_social         text NOT NULL,
    nombre_comercial     text,
    actividad_economica  text,
    direccion            text,
    provincia            text,
    municipio            text,
    telefono             text,
    correo               text,
    logo                 text,
    estado               text NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'inactiva')),
    -- false = la empresa 1 creada solo con EMISOR_RNC: Configuración →
    -- Empresa todavía no tiene datos guardados (como antes, sin fila).
    configurada          boolean NOT NULL DEFAULT true,
    creado_por           text,
    creado_en            timestamptz NOT NULL DEFAULT now(),
    actualizado_en       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS empresas_rnc_idx ON configuracion.empresas (rnc) WHERE rnc IS NOT NULL;

-- Quién entra a cada empresa (usuario de Supabase Auth), con qué rol y en
-- qué estado: 'activo' entra; 'inactivo' lo desactivó un administrador de
-- ESA empresa; 'invitado' (un usuario que ya era de otra empresa) entra
-- cuando acepta en Mis empresas; 'retirado' lo quitaron. Las filas no se
-- borran: un usuario sin NINGUNA fila es uno de antes de la multiempresa,
-- miembro de la empresa 1 (se escribe su fila en su primer inicio de
-- sesión, ver configuracion.multiempresa_legado).
CREATE TABLE IF NOT EXISTS configuracion.empresa_usuarios (
    empresa_id   integer NOT NULL REFERENCES configuracion.empresas (id) ON DELETE CASCADE,
    usuario_id   text NOT NULL,
    correo       text,
    rol          text NOT NULL DEFAULT 'usuario' CHECK (rol IN ('admin', 'usuario')),
    estado       text NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo', 'invitado', 'retirado')),
    agregado_por text,
    creado_en    timestamptz NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (empresa_id, usuario_id)
);
CREATE INDEX IF NOT EXISTS empresa_usuarios_usuario_idx ON configuracion.empresa_usuarios (usuario_id);

-- La última empresa que eligió cada usuario en el selector de la barra.
CREATE TABLE IF NOT EXISTS configuracion.usuario_empresa_actual (
    usuario_id      text PRIMARY KEY,
    empresa_id      integer NOT NULL REFERENCES configuracion.empresas (id) ON DELETE CASCADE,
    actualizado_en  timestamptz NOT NULL DEFAULT now()
);

-- La empresa 1, con los datos que ya tenía la instalación.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM configuracion.empresas WHERE id = 1) THEN
        -- (Por separado: plpgsql planifica la condición entera y la tabla
        -- puede no existir todavía si este servicio arranca primero.)
        IF to_regclass('configuracion.empresa') IS NOT NULL THEN
            INSERT INTO configuracion.empresas (id, rnc, razon_social, nombre_comercial, actividad_economica,
                                                direccion, provincia, municipio, telefono, correo, logo)
            SELECT 1,
                   COALESCE(NULLIF(regexp_replace(COALESCE(current_setting('kontara.emisor_rnc', true), ''), '[^0-9]', '', 'g'), ''),
                            NULLIF(e.rnc, '')),
                   e.razon_social, e.nombre_comercial, e.actividad_economica, e.direccion, e.provincia,
                   e.municipio, e.telefono, e.correo, e.logo
            FROM configuracion.empresa e;
        END IF;
        IF NOT EXISTS (SELECT 1 FROM configuracion.empresas WHERE id = 1) THEN
            INSERT INTO configuracion.empresas (id, rnc, razon_social, configurada)
            VALUES (
                1,
                NULLIF(regexp_replace(COALESCE(current_setting('kontara.emisor_rnc', true), ''), '[^0-9]', '', 'g'), ''),
                COALESCE(NULLIF(current_setting('kontara.emisor_razon_social', true), ''), 'Mi empresa'),
                false
            );
        END IF;
    END IF;
END;
$$;

-- Usuarios de antes de la multiempresa (una sola vez, al crear el registro).
-- Si la base es la de Supabase (esquema `auth` legible), cada usuario con
-- acceso a Kontara queda ya como miembro de la empresa 1, admin si tenía
-- kontara_admin o está en KONTARA_ADMIN_EMAILS (`kontara.admin_emails`) y,
-- si no había ningún admin, todos admin (antes cualquiera administraba
-- usuarios). Si no, se escriben en su primer inicio de sesión con
-- `previos_admin` = sin admins configurados (todos admin, igual que antes).
CREATE TABLE IF NOT EXISTS configuracion.multiempresa_legado (
    id             smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    migrado_en     timestamptz NOT NULL DEFAULT now(),
    desde_auth     boolean NOT NULL DEFAULT false,
    previos_admin  boolean NOT NULL DEFAULT false
);
DO $$
DECLARE
    admins text[] := ARRAY(
        SELECT lower(trim(x)) FROM unnest(string_to_array(COALESCE(current_setting('kontara.admin_emails', true), ''), ',')) x
        WHERE trim(x) <> '');
    desde_auth boolean := false;
BEGIN
    IF EXISTS (SELECT 1 FROM configuracion.multiempresa_legado) THEN
        RETURN;
    END IF;
    IF to_regclass('auth.users') IS NOT NULL THEN
        BEGIN
            EXECUTE $q$
                INSERT INTO configuracion.empresa_usuarios (empresa_id, usuario_id, correo, rol, agregado_por)
                SELECT 1, u.id::text, u.email,
                       CASE WHEN u.raw_app_meta_data ->> 'kontara_admin' = 'true' OR lower(u.email) = ANY ($1)
                            THEN 'admin' ELSE 'usuario' END,
                       'migración'
                FROM auth.users u
                WHERE u.raw_app_meta_data ->> 'kontara' = 'true' OR lower(u.email) = ANY ($1)
                ON CONFLICT DO NOTHING
            $q$ USING admins;
            desde_auth := true;
        EXCEPTION WHEN insufficient_privilege OR undefined_column OR undefined_table THEN
            RAISE NOTICE 'No se pudo leer auth.users (%): los usuarios de antes se registran al iniciar sesión', SQLERRM;
        END;
        IF desde_auth AND NOT EXISTS (
            SELECT 1 FROM configuracion.empresa_usuarios WHERE empresa_id = 1 AND rol = 'admin'
        ) THEN
            UPDATE configuracion.empresa_usuarios SET rol = 'admin' WHERE empresa_id = 1;
        END IF;
    END IF;
    INSERT INTO configuracion.multiempresa_legado (id, desde_auth, previos_admin)
    VALUES (1, desde_auth, NOT desde_auth AND cardinality(admins) = 0);
END;
$$;

-- Empresa de la conexión: la variable de sesión `kontara.empresa_id` (la pone
-- cada servicio en cada conexión del pool); vacía o sin poner = 1. Una
-- expresión simple (se expande en la consulta): la política queda como
-- `empresa_id = <valor>` y Postgres usa los índices (empresa_id, ...).
DO $$
BEGIN
    -- (Sin '...'::regprocedure: plpgsql lo resolvería antes de que exista.)
    IF COALESCE((SELECT position('v2' IN p.prosrc) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                 WHERE n.nspname = 'configuracion' AND p.proname = 'empresa_actual' AND p.pronargs = 0), 0) = 0 THEN
        CREATE OR REPLACE FUNCTION configuracion.empresa_actual() RETURNS integer
        LANGUAGE sql STABLE PARALLEL SAFE AS $f$
            -- v2
            SELECT COALESCE(NULLIF(current_setting('kontara.empresa_id', true), '')::integer, 1)
        $f$;
    END IF;
END;
$$;

-- Roles sin privilegios especiales con que trabajan las conexiones cuando el
-- usuario de la base es superusuario o tiene BYPASSRLS (que saltan las
-- políticas): kontara_app (una empresa) y kontara_todas (solo lectura de
-- todas: el token de un enlace del portal, Planes). Postgres 16 le da a quien
-- crea un rol con CREATEROLE solo ADMIN (sin SET): se pide SET explícito.
-- Sin permiso para crearlos o usarlos, se sigue sin ellos (ver
-- docs/MULTIEMPRESA.md: entonces solo se puede usar la empresa 1).
DO $$
DECLARE
    r text;
    pg16 boolean := current_setting('server_version_num')::integer >= 160000;
BEGIN
    FOREACH r IN ARRAY ARRAY['kontara_app', 'kontara_todas'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
            BEGIN
                EXECUTE format('CREATE ROLE %I NOLOGIN NOBYPASSRLS', r);
            EXCEPTION WHEN insufficient_privilege OR duplicate_object OR unique_violation THEN
                RAISE NOTICE 'No se pudo crear el rol %: %', r, SQLERRM;
            END;
        END IF;
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r)
           AND NOT (CASE WHEN pg16 THEN pg_has_role(current_user, r, 'SET')
                         ELSE pg_has_role(current_user, r, 'MEMBER') END) THEN
            BEGIN
                IF pg16 THEN
                    EXECUTE format('GRANT %I TO CURRENT_USER WITH INHERIT FALSE, SET TRUE', r);
                ELSE
                    EXECUTE format('GRANT %I TO CURRENT_USER', r);
                END IF;
            EXCEPTION WHEN insufficient_privilege OR invalid_grant_operation THEN
                RAISE NOTICE 'No se pudo dar el rol % a %: %', r, current_user, SQLERRM;
            END;
        END IF;
    END LOOP;
END;
$$;

-- Aísla una tabla por empresa: columna `empresa_id` (las filas existentes
-- quedan en la 1; las nuevas toman la de la conexión), los índices únicos
-- y claves de `unicos` pasan a incluir empresa_id (mismo nombre), y la
-- política `empresa_aislada` (FORCE: también para el dueño). Cada paso mira
-- el catálogo antes: en una tabla ya aislada no hace nada.
CREATE OR REPLACE FUNCTION configuracion.kontara_aislar(tabla regclass, unicos text[] DEFAULT '{}')
RETURNS void LANGUAGE plpgsql AS $f$
DECLARE
    esquema   text;
    nombre    text;
    definicion text;
    temporal  text;
BEGIN
    SELECT n.nspname INTO esquema FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE c.oid = tabla;
    IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = tabla AND attname = 'empresa_id' AND NOT attisdropped) THEN
        EXECUTE format('ALTER TABLE %s ADD COLUMN empresa_id integer NOT NULL DEFAULT 1', tabla);
    END IF;
    IF (SELECT pg_get_expr(d.adbin, d.adrelid) FROM pg_attrdef d
        JOIN pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
        WHERE d.adrelid = tabla AND a.attname = 'empresa_id') IS DISTINCT FROM 'configuracion.empresa_actual()' THEN
        EXECUTE format('ALTER TABLE %s ALTER COLUMN empresa_id SET DEFAULT configuracion.empresa_actual()', tabla);
    END IF;
    FOREACH nombre IN ARRAY unicos LOOP
        SELECT pg_get_constraintdef(oid) INTO definicion FROM pg_constraint WHERE conrelid = tabla AND conname = nombre;
        IF definicion IS NOT NULL THEN
            IF definicion NOT LIKE '%(empresa_id,%' THEN
                EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I, ADD CONSTRAINT %I %s',
                               tabla, nombre, nombre, regexp_replace(definicion, '\\(', '(empresa_id, '));
            END IF;
            CONTINUE;
        END IF;
        SELECT pg_get_indexdef(i.indexrelid) INTO definicion
        FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid
        WHERE i.indrelid = tabla AND c.relname = nombre AND i.indisunique;
        IF definicion IS NULL THEN
            RAISE EXCEPTION 'kontara_aislar: % no tiene el índice único %', tabla, nombre;
        END IF;
        IF definicion NOT LIKE '%(empresa_id,%' THEN
            temporal := left(nombre, 55) || '_me';
            EXECUTE format('DROP INDEX IF EXISTS %I.%I', esquema, temporal);
            EXECUTE regexp_replace(
                replace(definicion, ' INDEX ' || nombre || ' ON ', ' INDEX ' || temporal || ' ON '),
                'USING (\\w+) \\(', 'USING \\1 (empresa_id, ');
            EXECUTE format('DROP INDEX %I.%I', esquema, nombre);
            EXECUTE format('ALTER INDEX %I.%I RENAME TO %I', esquema, temporal, nombre);
        END IF;
    END LOOP;
    IF NOT (SELECT relrowsecurity AND relforcerowsecurity FROM pg_class WHERE oid = tabla) THEN
        EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY, FORCE ROW LEVEL SECURITY', tabla);
    END IF;
    -- (Una versión previa de esta rama tenía `OR todas_las_empresas()`, que
    -- impedía usar los índices: se rehace.)
    IF EXISTS (SELECT 1 FROM pg_policy WHERE polrelid = tabla AND polname = 'empresa_aislada'
               AND pg_get_expr(polqual, polrelid) LIKE '%todas_las_empresas%') THEN
        EXECUTE format('DROP POLICY empresa_aislada ON %s', tabla);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policy WHERE polrelid = tabla AND polname = 'empresa_aislada') THEN
        EXECUTE format(
            'CREATE POLICY empresa_aislada ON %s '
            'USING (empresa_id = configuracion.empresa_actual()) '
            'WITH CHECK (empresa_id = configuracion.empresa_actual())',
            tabla);
    END IF;
    -- Lectura de todas las empresas, solo para kontara_todas.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kontara_todas')
       AND NOT EXISTS (SELECT 1 FROM pg_policy WHERE polrelid = tabla AND polname = 'empresa_todas') THEN
        EXECUTE format('CREATE POLICY empresa_todas ON %s FOR SELECT TO kontara_todas USING (true)', tabla);
    END IF;
END;
$f$;

-- Permisos de kontara_app (lectura y escritura) y kontara_todas (solo
-- lectura) sobre las tablas y secuencias de unos esquemas (solo los que
-- falten). Sin los roles, no hace nada.
CREATE OR REPLACE FUNCTION configuracion.kontara_conceder(esquemas text[])
RETURNS void LANGUAGE plpgsql AS $f$
DECLARE
    r record;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kontara_app') THEN
        RETURN;
    END IF;
    FOR r IN SELECT nspname FROM pg_namespace
             WHERE nspname = ANY (esquemas) AND NOT has_schema_privilege('kontara_app', oid, 'USAGE') LOOP
        EXECUTE format('GRANT USAGE ON SCHEMA %I TO kontara_app', r.nspname);
    END LOOP;
    FOR r IN SELECT c.oid::regclass AS objeto, c.relkind FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
             WHERE n.nspname = ANY (esquemas) AND c.relkind IN ('r', 'p', 'v', 'S') LOOP
        IF r.relkind = 'S' THEN
            IF NOT (has_sequence_privilege('kontara_app', r.objeto::oid, 'USAGE')
                    AND has_sequence_privilege('kontara_app', r.objeto::oid, 'UPDATE')) THEN
                EXECUTE format('GRANT USAGE, SELECT, UPDATE ON SEQUENCE %s TO kontara_app', r.objeto);
            END IF;
        ELSIF NOT (has_table_privilege('kontara_app', r.objeto::oid, 'SELECT')
                   AND has_table_privilege('kontara_app', r.objeto::oid, 'INSERT')
                   AND has_table_privilege('kontara_app', r.objeto::oid, 'UPDATE')
                   AND has_table_privilege('kontara_app', r.objeto::oid, 'DELETE')) THEN
            EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %s TO kontara_app', r.objeto);
        END IF;
    END LOOP;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kontara_todas') THEN
        RETURN;
    END IF;
    FOR r IN SELECT nspname FROM pg_namespace
             WHERE nspname = ANY (esquemas) AND NOT has_schema_privilege('kontara_todas', oid, 'USAGE') LOOP
        EXECUTE format('GRANT USAGE ON SCHEMA %I TO kontara_todas', r.nspname);
    END LOOP;
    FOR r IN SELECT c.oid::regclass AS objeto FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
             WHERE n.nspname = ANY (esquemas) AND c.relkind IN ('r', 'p', 'v')
               AND NOT has_table_privilege('kontara_todas', c.oid, 'SELECT') LOOP
        EXECUTE format('GRANT SELECT ON TABLE %s TO kontara_todas', r.objeto);
    END LOOP;
END;
$f$;

SELECT configuracion.kontara_conceder(ARRAY['configuracion']);
"""


async def preparar_semilla(
    conn: Any, *, emisor_rnc: str = "", razon_social: str = "", admin_emails: str = ""
) -> None:
    """Datos de la empresa 1 y de los usuarios de antes, si hay que crearlos
    (dentro de la transacción de la migración: set_config local)."""
    await conn.execute(
        "SELECT set_config('kontara.emisor_rnc', $1, true), set_config('kontara.emisor_razon_social', $2, true),"
        " set_config('kontara.admin_emails', $3, true)",
        emisor_rnc or "",
        razon_social or "",
        admin_emails or "",
    )


async def tomar_lock(conn: Any) -> None:
    """El lock compartido. Cada servicio lo toma AL EMPEZAR su migración,
    antes de cualquier lock de tabla: así dos servicios que arrancan a la vez
    se turnan en vez de esperarse con tablas bloqueadas (con el
    lock_timeout de la migración, el que no lo obtiene reintenta)."""
    await conn.execute("SELECT pg_advisory_xact_lock($1)", LOCK_MULTIEMPRESA)


async def aplicar(
    conn: Any, ddl_servicio: str, *, emisor_rnc: str = "", razon_social: str = "", admin_emails: str = ""
) -> None:
    """DDL común + el del servicio. Llamarlo dentro de la transacción de la
    migración del servicio, después de `tomar_lock` (lo vuelve a tomar: es
    reentrante en la misma transacción)."""
    await tomar_lock(conn)
    await preparar_semilla(conn, emisor_rnc=emisor_rnc, razon_social=razon_social, admin_emails=admin_emails)
    await conn.execute(DDL_MULTIEMPRESA)
    await conn.execute(ddl_servicio)
